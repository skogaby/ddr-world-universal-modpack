#!/usr/bin/env python3
"""Generate the song-title glyph table for StepMania native titles.

The game draws wheel/stage titles with its own KBF bitmap fonts
(`2d_font_songtitle_m` and `_s`, docs/kbf_font_format.md). A StepMania
song's native `#TITLE` (CJK, accented Latin, …) is shown only when EVERY
codepoint has a glyph in BOTH fonts; otherwise the loader falls back to
`#TITLETRANSLIT`. This script reads the KBF glyph tables out of the game's
own font arcs and writes the intersection as sorted inclusive ranges into a
generated, dependency-free Rust file.

Usage:
  python3 scripts/gen_title_glyph_table.py            # uses $DDR_WORLD_INSTALL
  python3 scripts/gen_title_glyph_table.py --install <game contents dir>
  python3 scripts/gen_title_glyph_table.py --check    # exit 1 if the file is stale

Output: src/core/sm/title_glyphs.rs (never hand-edit).
"""

import argparse
import os
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from unpack_arc import ARC  # noqa: E402

FONTS = ("2d_font_songtitle_m", "2d_font_songtitle_s")
OUT = REPO / "src" / "core" / "sm" / "title_glyphs.rs"


def kbf_codes(kbf: bytes) -> set:
    if kbf[:4] != b"kbf\0":
        raise SystemExit("not a KBF file")
    (count,) = struct.unpack_from("<I", kbf, 0x14)
    codes = set()
    for i in range(count):
        off = 32 + 16 * i
        if off + 16 > len(kbf):
            raise SystemExit("KBF glyph table truncated")
        (code,) = struct.unpack_from("<H", kbf, off)
        codes.add(code)
    return codes


def font_codes(install: Path, name: str) -> set:
    arc_path = install / "data" / "arc" / f"{name}.arc"
    arc = ARC(arc_path.read_bytes())
    kbf = arc.get_file(f"data/font/{name}.kbf")
    if kbf is None:
        raise SystemExit(f"{arc_path.name}: no data/font/{name}.kbf member")
    return kbf_codes(kbf)


def ranges(codes):
    out = []
    for c in sorted(codes):
        if out and c == out[-1][1] + 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def render(rs, counts):
    lines = [
        "//! Codepoints the game's song-title fonts can draw — GENERATED by",
        "//! `scripts/gen_title_glyph_table.py` from the KBF glyph tables of",
        f"//! {' and '.join(f'`{f}`' for f in FONTS)} (intersection); do not",
        "//! edit by hand, re-run the script after a font change.",
        "//!",
        f"//! Glyphs per font: {', '.join(f'{f} {n}' for f, n in counts)}; drawable in",
        f"//! both: {sum(b - a + 1 for a, b in rs)} codepoints in {len(rs)} ranges.",
        "//!",
        "//! Pure, dependency-free; consulted by `services::stepmania::convert::display_title`.",
        "",
        "/// Sorted, disjoint, inclusive BMP ranges.",
        "pub const RANGES: &[(u16, u16)] = &[",
    ]
    # One tuple per line: the layout rustfmt settles on, so `cargo fmt` is a no-op.
    for a, b in rs:
        lines.append(f"    (0x{a:04X}, 0x{b:04X}),")
    lines += [
        "];",
        "",
        "/// Whether the title fonts have a glyph for `c`.",
        "#[must_use]",
        "pub fn has_glyph(c: char) -> bool {",
        "    let Ok(cp) = u16::try_from(u32::from(c)) else {",
        "        return false;",
        "    };",
        "    RANGES",
        "        .binary_search_by(|&(lo, hi)| {",
        "            if hi < cp {",
        "                std::cmp::Ordering::Less",
        "            } else if lo > cp {",
        "                std::cmp::Ordering::Greater",
        "            } else {",
        "                std::cmp::Ordering::Equal",
        "            }",
        "        })",
        "        .is_ok()",
        "}",
        "",
        "/// Whether every character of `s` is drawable (empty = true).",
        "#[must_use]",
        "pub fn renderable(s: &str) -> bool {",
        "    s.chars().all(has_glyph)",
        "}",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    #[test]",
        "    fn ranges_sorted_disjoint() {",
        "        for w in RANGES.windows(2) {",
        "            assert!(w[0].0 <= w[0].1 && w[0].1 < w[1].0, \"{:?}\", w);",
        "        }",
        "    }",
        "",
        "    #[test]",
        "    fn ascii_and_kana_drawable_astral_not() {",
        "        assert!(renderable(\"Put Your Faith In Me\"));",
        "        assert!(renderable(\"\\u{3042}\\u{30A2}\")); // あア",
        "        assert!(!has_glyph('\\u{1F600}'));",
        "        assert!(!has_glyph('\\u{0007}'));",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--install", help="game contents dir (default: $DDR_WORLD_INSTALL)")
    ap.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = ap.parse_args()
    root = args.install or os.environ.get("DDR_WORLD_INSTALL")
    if not root:
        raise SystemExit("set DDR_WORLD_INSTALL or pass --install")
    install = Path(root)
    sets = [(f, font_codes(install, f)) for f in FONTS]
    common = set.intersection(*(s for _, s in sets))
    common = {c for c in common if c >= 0x20 and not (0xD800 <= c <= 0xDFFF)}
    text = render(ranges(common), [(f, len(s)) for f, s in sets])
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is stale — re-run the generator", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(REPO)} up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(common)} codepoints, {len(ranges(common))} ranges")
    return 0


if __name__ == "__main__":
    sys.exit(main())
