/// BSI byteswap + string-table cipher removal — the same "fully
/// descrambled" shape the game's afp_patcher seam sees (docs/afp_system.md
/// §1). String table region: offset @48, size @52 (u32 LE).
fn descramble(afp_path: &str, bsi_path: &str) -> Option<Vec<u8>> {
    let mut data = std::fs::read(afp_path).ok()?;
    let bsi = std::fs::read(bsi_path).ok()?;
    afp::apply_bsi(&mut data, &bsi);
    let st_off = u32::from_le_bytes(data.get(48..52)?.try_into().ok()?) as usize;
    let st_size = u32::from_le_bytes(data.get(52..56)?.try_into().ok()?) as usize;
    let table = data.get(st_off..st_off.checked_add(st_size)?)?.to_vec();
    let plain = ap2::decode_string_table(&table);
    data[st_off..st_off + st_size].copy_from_slice(&plain);
    Some(data)
}

fn file_name(p: &str) -> String {
    std::path::Path::new(p)
        .file_name()
        .map(|f| f.to_string_lossy().into_owned())
        .unwrap_or_else(|| p.to_string())
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mode = args.first().map(String::as_str).unwrap_or("");
    if mode == "edit-demo" {
        if args.len() != 5 {
            eprintln!("usage: ap2check edit-demo <afp> <bsi> <out_afp> <out_bsi>");
            std::process::exit(2);
        }
        std::process::exit(edit_demo(&args[1], &args[2], &args[3], &args[4]));
    }
    if mode == "smarv-patch" {
        if args.len() != 5 {
            eprintln!("usage: ap2check smarv-patch <afp> <bsi> <geo_dir> <out_afp>");
            std::process::exit(2);
        }
        std::process::exit(smarv_patch(&args[1], &args[2], &args[3], &args[4]));
    }
    if mode == "smarv-fc" {
        if args.len() != 4 {
            eprintln!("usage: ap2check smarv-fc <afp> <bsi> <geo_dir>");
            std::process::exit(2);
        }
        std::process::exit(smarv_fc(&args[1], &args[2], &args[3]));
    }
    if mode == "smarv-emblem" {
        if args.len() != 5 {
            eprintln!("usage: ap2check smarv-emblem <afp> <bsi> <geo_dir> <out_afp>");
            std::process::exit(2);
        }
        std::process::exit(smarv_emblem(&args[1], &args[2], &args[3], &args[4]));
    }
    if mode == "smarv-rows" {
        if args.len() != 6 {
            eprintln!("usage: ap2check smarv-rows <afp> <bsi> <rows d:ty:dy,..> <expected_each> <out_afp>");
            std::process::exit(2);
        }
        std::process::exit(smarv_rows(&args[1], &args[2], &args[3], &args[4], &args[5]));
    }
    if mode == "geo-rewrite" {
        if args.len() != 5 {
            eprintln!("usage: ap2check geo-rewrite <geo_in> <old_label> <new_label> <geo_out>");
            std::process::exit(2);
        }
        std::process::exit(geo_rewrite(&args[1], &args[2], &args[3], &args[4]));
    }
    let pairs = &args[1..];
    if !matches!(mode, "roundtrip" | "info") || pairs.len() % 2 != 0 {
        eprintln!("usage: ap2check roundtrip|info <afp> <bsi> [<afp> <bsi> ...]");
        std::process::exit(2);
    }
    let mut fail = 0u32;
    for pair in pairs.chunks(2) {
        let name = file_name(&pair[0]);
        let Some(data) = descramble(&pair[0], &pair[1]) else {
            println!("FAIL {name}: descramble");
            fail += 1;
            continue;
        };
        let Some(doc) = ap2::Ap2Doc::parse(&data) else {
            println!("FAIL {name}: parse -> None");
            fail += 1;
            continue;
        };
        match mode {
            "roundtrip" => {
                let Some(out) = doc.serialize() else {
                    println!("FAIL {name}: serialize -> None");
                    fail += 1;
                    continue;
                };
                if out == data {
                    println!(
                        "PASS {name}: {} bytes, exported '{}'",
                        data.len(),
                        doc.exported_name()
                    );
                } else {
                    let first = out.iter().zip(data.iter()).position(|(a, b)| a != b);
                    println!(
                        "FAIL {name}: byte mismatch (len {} vs {}, first diff @ {:?})",
                        out.len(),
                        data.len(),
                        first
                    );
                    fail += 1;
                }
            }
            "info" => {
                // Normalized structural lines — must match what Leg B
                // derives from bemaniutils parseafp JSON.
                println!("file={name}");
                println!("exported_name={}", doc.exported_name());
                println!("frames={}", doc.root.frames.len());
                for (i, f) in doc.root.frames.iter().enumerate() {
                    println!("frame[{i}]={},{}", f.start_tag, f.tag_count);
                }
            }
            _ => unreachable!(),
        }
    }
    std::process::exit(if fail > 0 { 1 } else { 0 });
}

/// Source character ids referenced by the PlaceObjects of the labeled
/// segment (label frame .. next label / section end).
fn segment_source_ids(sec: &ap2::TagSection, label: &str) -> Vec<u16> {
    let Some(start) = sec.label_frame(label) else {
        return Vec::new();
    };
    let start = start as usize;
    let end = sec
        .labels
        .iter()
        .map(|l| l.frame as usize)
        .filter(|f| *f > start)
        .min()
        .unwrap_or(sec.frames.len());
    let mut ids = Vec::new();
    for f in &sec.frames[start..end.min(sec.frames.len())] {
        for i in f.start_tag..(f.start_tag + f.tag_count) {
            if let Some(ap2::Tag::PlaceObject(po)) = sec.tags.get(i as usize) {
                if let Some(v) = po.view() {
                    if let Some(id) = v.source_tag_id {
                        if !ids.contains(&id) {
                            ids.push(id);
                        }
                    }
                }
            }
        }
    }
    ids
}

/// Step-4 task-02 (Leg D): run the REAL word-segment recipe — the same
/// core/ap2 fn the DLL's dance_judge patch calls — on a real template and
/// write the patched file (string table re-scrambled) for bemaniutils
/// consumption. Prints the resolved/allocated ids + segment geometry.
fn smarv_patch(afp: &str, bsi: &str, geo_dir: &str, out_afp: &str) -> i32 {
    let Some(data) = descramble(afp, bsi) else {
        println!("FAIL smarv-patch: descramble");
        return 1;
    };
    let Some(mut doc) = ap2::Ap2Doc::parse(&data) else {
        println!("FAIL smarv-patch: parse");
        return 1;
    };
    // Resolve the word shape through the SHARED geo-first resolver — the
    // exact code path the DLL's assets.rs staging runs (deploy #3 fix: a
    // parallel harness-only resolution masked the DLL resolver's v3 break).
    let Some((word_shape_id, donor_region)) =
        doc.find_word_shape_by_geo("in_marvelous", "marvelous", |geo_name| {
            let bytes = std::fs::read(format!("{geo_dir}/{geo_name}")).ok()?;
            geo::labels(&bytes)
        })
    else {
        println!("FAIL smarv-patch: word chain unresolved (shared resolver)");
        return 1;
    };
    println!("word_shape_id={word_shape_id}");
    println!("donor_region={donor_region}");
    // The DLL's exact options (assets::word_clone_opts(false)): mute the
    // additive marvelous_ef self-glow in the cloned chain, stock untouched.
    // Muted-or-nothing here — the harness must prove the mute applies on
    // the REAL template (the DLL's runtime fallback to an unmuted clone is
    // for unknown skins).
    let Some(ids) = doc.clone_word_segment_with_new_shape_ex(
        "in_marvelous",
        "in_smarvelous",
        word_shape_id,
        ap2::WordCloneOpts {
            mute_additive_glow: true,
            mute_source_additive_glow: false,
        },
    ) else {
        println!("FAIL smarv-patch: recipe returned None");
        return 1;
    };
    println!("muted_records={}", ids.muted_records);

    // Second pass on a fresh parse: the "Marvelous Shimmer OFF" shape
    // (assets::word_clone_opts(true)) must ALSO apply on the real template
    // — same ids, stock chain silenced too, output size unchanged (in-place
    // edits only).
    {
        let Some(mut doc2) = ap2::Ap2Doc::parse(&data) else {
            println!("FAIL smarv-patch: parse (shimmer-off pass)");
            return 1;
        };
        let Some(ids2) = doc2.clone_word_segment_with_new_shape_ex(
            "in_marvelous",
            "in_smarvelous",
            word_shape_id,
            ap2::WordCloneOpts {
                mute_additive_glow: true,
                mute_source_additive_glow: true,
            },
        ) else {
            println!("FAIL smarv-patch: shimmer-off recipe returned None");
            return 1;
        };
        if (ids2.new_shape_id, ids2.new_sprite_id, ids2.muted_records)
            != (ids.new_shape_id, ids.new_sprite_id, ids.muted_records)
        {
            println!("FAIL smarv-patch: shimmer-off pass changed the allocated ids / clone mute count");
            return 1;
        }
        println!("stock_muted_records={}", ids2.muted_source_records);
        let Some(out2) = doc2.serialize() else {
            println!("FAIL smarv-patch: shimmer-off serialize");
            return 1;
        };
        let Some(re2) = ap2::Ap2Doc::parse(&out2) else {
            println!("FAIL smarv-patch: shimmer-off re-parse");
            return 1;
        };
        let stock2 = re2
            .find_sprite_by_label("in_smarvelous")
            .and_then(|p| re2.section(&p).map(|s| s.clone()))
            .and_then(|sec| {
                let sp = sec.tags.iter().find_map(|t| match t {
                    ap2::Tag::DefineSprite(s) if s.id == ids2.word_sprite_id => Some(s),
                    _ => None,
                })?;
                let mut keys: Vec<(u16, u16)> = Vec::new();
                let mut alphas = Vec::new();
                for t in &sp.section.tags {
                    let ap2::Tag::PlaceObject(po) = t else { continue };
                    let v = po.view()?;
                    let key = (v.object_id, v.depth);
                    if v.flags & 0x1 == 0 && v.blend == Some(8) {
                        keys.push(key);
                    }
                    if keys.contains(&key) {
                        if let Some(m) = v.mult_color {
                            alphas.push(m.alpha);
                        }
                    }
                }
                Some(alphas)
            })
            .unwrap_or_default();
        println!("shimmer_off_stock_additive_alphas={stock2:?}");
        if stock2.is_empty() || stock2.iter().any(|&a| a != 0) {
            println!("FAIL smarv-patch: shimmer-off pass left the stock additive glow unmuted");
            return 1;
        }
        // Size parity with the shimmer-on output is asserted after that
        // output is serialized below.
        println!("shimmer_off_out_len={}", out2.len());
    }
    let Some(mut out) = doc.serialize() else {
        println!("FAIL smarv-patch: serialize");
        return 1;
    };
    println!("shimmer_on_out_len={}", out.len());
    let Some(re) = ap2::Ap2Doc::parse(&out) else {
        println!("FAIL smarv-patch: re-parse");
        return 1;
    };
    let Some(path) = re.find_sprite_by_label("in_smarvelous") else {
        println!("FAIL smarv-patch: in_smarvelous missing");
        return 1;
    };
    let Some(sec) = re.section(&path) else {
        println!("FAIL smarv-patch: section");
        return 1;
    };
    let Some(label_frame) = sec.label_frame("in_smarvelous") else {
        println!("FAIL smarv-patch: label frame");
        return 1;
    };
    println!("word_sprite_id={}", ids.word_sprite_id);
    println!("new_shape_id={}", ids.new_shape_id);
    println!("new_sprite_id={}", ids.new_sprite_id);
    println!("label_frame={label_frame}");
    println!("section_frames={}", sec.frames.len());

    // Mute proof on the serialized output: every additive-blend object in
    // the CLONED top sprite has mult alpha 0 on all its records; the STOCK
    // word sprite still carries a non-zero additive alpha (the pulse is
    // real and was left alone).
    let additive_alphas = |sprite_id: u16| -> Option<Vec<i32>> {
        let sp = sec.tags.iter().find_map(|t| match t {
            ap2::Tag::DefineSprite(s) if s.id == sprite_id => Some(s),
            _ => None,
        })?;
        let mut keys: Vec<(u16, u16)> = Vec::new();
        let mut alphas = Vec::new();
        for t in &sp.section.tags {
            let ap2::Tag::PlaceObject(po) = t else { continue };
            let v = po.view()?;
            let key = (v.object_id, v.depth);
            if v.flags & 0x1 == 0 && v.blend == Some(8) {
                keys.push(key);
            }
            if keys.contains(&key) {
                if let Some(m) = v.mult_color {
                    alphas.push(m.alpha);
                }
            }
        }
        Some(alphas)
    };
    let cloned = additive_alphas(ids.new_sprite_id).unwrap_or_default();
    let stock = additive_alphas(ids.word_sprite_id).unwrap_or_default();
    println!("cloned_additive_alphas={cloned:?}");
    println!("stock_additive_alphas={stock:?}");
    if cloned.is_empty() || cloned.iter().any(|&a| a != 0) {
        println!("FAIL smarv-patch: cloned additive glow not muted");
        return 1;
    }
    if !stock.iter().any(|&a| a != 0) {
        println!("FAIL smarv-patch: stock additive glow altered (or absent)");
        return 1;
    }

    // Re-scramble the string table for bemaniutils consumption (its SWF
    // parser always runs the cipher).
    let st_off = u32::from_le_bytes(out[48..52].try_into().unwrap()) as usize;
    let st_size = u32::from_le_bytes(out[52..56].try_into().unwrap()) as usize;
    let scrambled = ap2::encode_string_table(&out[st_off..st_off + st_size]);
    out[st_off..st_off + st_size].copy_from_slice(&scrambled);
    if std::fs::write(out_afp, &out).is_err() {
        println!("FAIL smarv-patch: write {out_afp}");
        return 1;
    }
    println!("smarv-patch OK: wrote {out_afp} ({} bytes)", out.len());
    0
}

/// Step-7 (Leg F): the REAL row-repositioning transform — the same
/// core/ap2 method the DLL's body_tab_detail_result patch calls — on a
/// real template. Rows arrive as "depth:ty:dy,..." (extracted by the
/// script from results_score.rs::ROW_MOVES so the table has ONE source of
/// truth). Verifies the shifted counts, serializes, and writes the
/// re-scrambled output for the bemaniutils position cross-check.
fn smarv_rows(afp: &str, bsi: &str, rows: &str, expected: &str, out_afp: &str) -> i32 {
    let Some(data) = descramble(afp, bsi) else {
        println!("FAIL smarv-rows: descramble");
        return 1;
    };
    let Some(mut doc) = ap2::Ap2Doc::parse(&data) else {
        println!("FAIL smarv-rows: parse");
        return 1;
    };
    let mut table: Vec<(u16, i32, i32)> = Vec::new();
    for entry in rows.split(',') {
        let parts: Vec<&str> = entry.split(':').collect();
        let (Some(d), Some(ty), Some(dy)) = (
            parts.first().and_then(|s| s.parse().ok()),
            parts.get(1).and_then(|s| s.parse().ok()),
            parts.get(2).and_then(|s| s.parse().ok()),
        ) else {
            println!("FAIL smarv-rows: bad row entry '{entry}'");
            return 1;
        };
        table.push((d, ty, dy));
    }
    let Ok(expected_each) = expected.parse::<usize>() else {
        println!("FAIL smarv-rows: bad expected_each '{expected}'");
        return 1;
    };
    if doc.shift_row_translates(&table, expected_each).is_none() {
        println!("FAIL smarv-rows: shift_row_translates refused (count mismatch?)");
        return 1;
    }
    let Some(mut out) = doc.serialize() else {
        println!("FAIL smarv-rows: serialize");
        return 1;
    };
    // Re-parse and verify each row now matches at the SHIFTED position
    // (and no longer at the stock one).
    let Some(re) = ap2::Ap2Doc::parse(&out) else {
        println!("FAIL smarv-rows: re-parse");
        return 1;
    };
    fn count_rows(doc: &ap2::Ap2Doc, depth: u16, ty: i32) -> usize {
        fn walk(sec: &ap2::TagSection, depth: u16, ty: i32) -> usize {
            let mut n = 0;
            for tag in &sec.tags {
                match tag {
                    ap2::Tag::PlaceObject(p) => {
                        if let Some(v) = p.view() {
                            if v.depth == depth && v.translate.map(|(_, y)| y) == Some(ty) {
                                n += 1;
                            }
                        }
                    }
                    ap2::Tag::DefineSprite(s) => n += walk(&s.section, depth, ty),
                    _ => {}
                }
            }
            n
        }
        walk(&doc.root, depth, ty)
    }
    for &(depth, ty, dy) in &table {
        let moved = count_rows(&re, depth, ty + dy);
        let stale = count_rows(&re, depth, ty);
        if moved != expected_each || stale != 0 {
            println!(
                "FAIL smarv-rows: d{depth} ty{ty}+{dy}: moved={moved} (want {expected_each}), stale={stale}"
            );
            return 1;
        }
        println!("row d{depth}: ty {ty} -> {} ({moved} records)", ty + dy);
    }
    // Re-scramble the string table for bemaniutils consumption.
    let st_off = u32::from_le_bytes(out[48..52].try_into().unwrap()) as usize;
    let st_size = u32::from_le_bytes(out[52..56].try_into().unwrap()) as usize;
    let scrambled = ap2::encode_string_table(&out[st_off..st_off + st_size]);
    out[st_off..st_off + st_size].copy_from_slice(&scrambled);
    if std::fs::write(out_afp, &out).is_err() {
        println!("FAIL smarv-rows: write {out_afp}");
        return 1;
    }
    println!("smarv-rows OK: wrote {out_afp} ({} bytes)", out.len());
    0
}

/// Step-6 (Leg E): geo-first art-shape resolution + the multi-shape
/// recipe on a REAL dance_fullcombo template (the DLL's staging path).
fn smarv_fc(afp: &str, bsi: &str, geo_dir: &str) -> i32 {
    let Some(data) = descramble(afp, bsi) else {
        println!("FAIL smarv-fc: descramble");
        return 1;
    };
    let Some(mut doc) = ap2::Ap2Doc::parse(&data) else {
        println!("FAIL smarv-fc: parse");
        return 1;
    };
    // Geo-first: shapes whose geo has a region whose last token starts
    // with "mar" (the DLL's fc_region_rename rule).
    let mut shape_ids: Vec<u16> = Vec::new();
    for tag in &doc.root.tags {
        let ap2::Tag::Shape(shape) = tag else { continue };
        let geo_name = format!("{}_shape{}", doc.exported_name(), shape.id);
        let Ok(bytes) = std::fs::read(format!("{geo_dir}/{geo_name}")) else {
            continue;
        };
        let Some(labels) = geo::labels(&bytes) else { continue };
        if labels.iter().any(|l| {
            l.rsplit_once('_').map(|(_, t)| t.starts_with("mar")).unwrap_or(false)
        }) {
            shape_ids.push(shape.id);
        }
    }
    if shape_ids.len() != 4 {
        println!("FAIL smarv-fc: resolved {} art shapes (want 4)", shape_ids.len());
        return 1;
    }
    let Some(ids) =
        doc.clone_segment_with_new_shapes("marbelous_in", "s_marbelous_in", &shape_ids)
    else {
        println!("FAIL smarv-fc: recipe returned None");
        return 1;
    };
    let Some(out) = doc.serialize() else {
        println!("FAIL smarv-fc: serialize");
        return 1;
    };
    let Some(re) = ap2::Ap2Doc::parse(&out) else {
        println!("FAIL smarv-fc: re-parse");
        return 1;
    };
    // The new label must exist in EVERY section that carries the source
    // label (root + inner timeline), and every label table stays sorted.
    fn check(sec: &ap2::TagSection, path: &str, errs: &mut Vec<String>) {
        let has_src = sec.labels.iter().any(|l| l.name == "marbelous_in");
        let has_new = sec.labels.iter().any(|l| l.name == "s_marbelous_in");
        if has_src && !has_new {
            errs.push(format!("{path}: source label without clone"));
        }
        let mut names: Vec<&str> = sec.labels.iter().map(|l| l.name.as_str()).collect();
        let mut sorted = names.clone();
        sorted.sort();
        if names != sorted {
            errs.push(format!("{path}: label table unsorted"));
        }
        names.clear();
        for (i, t) in sec.tags.iter().enumerate() {
            if let ap2::Tag::DefineSprite(sp) = t {
                check(&sp.section, &format!("{path}/{i}"), errs);
            }
        }
    }
    let mut errs = Vec::new();
    check(&re.root, "root", &mut errs);
    if !errs.is_empty() {
        for e in &errs {
            println!("FAIL smarv-fc: {e}");
        }
        return 1;
    }
    println!(
        "smarv-fc OK: shapes {:?} -> {:?}, {} sprite clone(s), {} bytes",
        shape_ids,
        ids.shapes.iter().map(|(_, n)| *n).collect::<Vec<_>>(),
        ids.sprites.len(),
        out.len()
    );
    0
}

/// Step-9 (Leg G): the REAL FC-emblem recipe — geo-first word-shape
/// resolution + the multi-shape clone with the emblem options (HSL-update
/// drop + DoAction loop retarget) on the REAL result_root template, the
/// same call shape the DLL's patch fn runs.
fn smarv_emblem(afp: &str, bsi: &str, geo_dir: &str, out_afp: &str) -> i32 {
    let Some(data) = descramble(afp, bsi) else {
        println!("FAIL smarv-emblem: descramble");
        return 1;
    };
    let Some(mut doc) = ap2::Ap2Doc::parse(&data) else {
        println!("FAIL smarv-emblem: parse");
        return 1;
    };
    // Geo-first word-shape resolution (the DLL's fc_region_rename rule);
    // result_root must resolve EXACTLY ONE (shape 202 -> scre_fc_marvelous).
    let mut shape_ids: Vec<u16> = Vec::new();
    for tag in &doc.root.tags {
        let ap2::Tag::Shape(shape) = tag else { continue };
        let geo_name = format!("{}_shape{}", doc.exported_name(), shape.id);
        let Ok(bytes) = std::fs::read(format!("{geo_dir}/{geo_name}")) else {
            continue;
        };
        let Some(labels) = geo::labels(&bytes) else { continue };
        if labels.iter().any(|l| {
            l.rsplit_once('_').map(|(_, t)| t.starts_with("mar")).unwrap_or(false)
        }) {
            shape_ids.push(shape.id);
        }
    }
    if shape_ids.len() != 1 {
        println!("FAIL smarv-emblem: resolved {} word shapes (want 1)", shape_ids.len());
        return 1;
    }
    let opts = ap2::SegmentCloneOpts {
        drop_hsl_updates_on_remapped: true,
        retarget_actions: true,
    };
    let Some(ids) = doc.clone_segment_with_new_shapes_ex("loop_mfc", "loop_smfc", &shape_ids, opts)
    else {
        println!("FAIL smarv-emblem: recipe returned None");
        return 1;
    };
    let Some(out) = doc.serialize() else {
        println!("FAIL smarv-emblem: serialize");
        return 1;
    };
    let Some(re) = ap2::Ap2Doc::parse(&out) else {
        println!("FAIL smarv-emblem: re-parse");
        return 1;
    };
    // Structural checks on every section carrying the source label.
    let new_sprites: Vec<u16> = ids.sprites.iter().map(|(_, n)| *n).collect();
    fn segment_place_stats(
        sec: &ap2::TagSection,
        label: &str,
        cloned_sprites: &[u16],
    ) -> Option<(usize, usize, Vec<u16>)> {
        // (hsl_updates_on_cloned, do_action_count, cloned create object ids)
        let start = sec.label_frame(label)? as usize;
        let end = sec
            .labels
            .iter()
            .map(|l| l.frame as usize)
            .filter(|f| *f > start)
            .min()
            .unwrap_or(sec.frames.len());
        let mut keys: Vec<(u16, u16)> = Vec::new();
        let mut creates: Vec<u16> = Vec::new();
        let mut hsl = 0usize;
        let mut actions = 0usize;
        for f in &sec.frames[start..end.min(sec.frames.len())] {
            let s = f.start_tag as usize;
            for t in sec.tags.get(s..s + f.tag_count as usize)? {
                match t {
                    ap2::Tag::PlaceObject(po) => {
                        let v = po.view()?;
                        if v.flags & 0x1 == 0 {
                            if let Some(src) = v.source_tag_id {
                                if cloned_sprites.contains(&src) {
                                    keys.push((v.object_id, v.depth));
                                    creates.push(v.object_id);
                                }
                            }
                        } else if v.flags & 0x2000_0000 != 0
                            && keys.contains(&(v.object_id, v.depth))
                        {
                            hsl += 1;
                        }
                    }
                    ap2::Tag::Opaque(o) if o.tag_id == 0x7A => actions += 1,
                    _ => {}
                }
            }
        }
        Some((hsl, actions, creates))
    }
    fn walk(
        sec: &ap2::TagSection,
        path: &str,
        re: &ap2::Ap2Doc,
        new_sprites: &[u16],
        errs: &mut Vec<String>,
        stats: &mut Vec<String>,
    ) {
        let has_src = sec.labels.iter().any(|l| l.name == "loop_mfc");
        let has_new = sec.labels.iter().any(|l| l.name == "loop_smfc");
        if has_src && !has_new {
            errs.push(format!("{path}: source label without clone"));
        }
        if has_new {
            // 1) The cloned word object carries NO HSL updates (static
            //    violet), while the stock segment still animates.
            let clone = segment_place_stats(sec, "loop_smfc", new_sprites);
            match clone {
                Some((hsl, actions, creates)) => {
                    if hsl != 0 {
                        errs.push(format!("{path}: {hsl} HSL update(s) survived the drop"));
                    }
                    if actions == 0 {
                        errs.push(format!("{path}: cloned segment lost its DoAction"));
                    }
                    if creates.is_empty() {
                        errs.push(format!("{path}: no cloned-word create in the segment"));
                    }
                    // 3) id==death-frame: cloned creates outlive the label.
                    if let Some(lf) = sec.label_frame("loop_smfc") {
                        for id in &creates {
                            if *id <= lf {
                                errs.push(format!("{path}: create id {id} <= label frame {lf}"));
                            }
                        }
                    }
                    stats.push(format!(
                        "{path}: hsl_dropped_ok, {actions} action(s), creates {creates:?}"
                    ));
                }
                None => errs.push(format!("{path}: cloned segment unreadable")),
            }
            // 2) Every DoAction in the cloned segment referencing a loop
            //    label must point at loop_smfc (the retarget).
            if let Some(start) = sec.label_frame("loop_smfc") {
                let start = start as usize;
                for f in &sec.frames[start..] {
                    let s = f.start_tag as usize;
                    for t in &sec.tags[s..(s + f.tag_count as usize).min(sec.tags.len())] {
                        if let ap2::Tag::Opaque(o) = t {
                            if o.tag_id == 0x7A && o.data.len() >= 6 && o.data[0] == 0xFF
                                && o.data[1] & 1 == 1
                            {
                                let n = u16::from_le_bytes([o.data[2], o.data[3]]) as usize;
                                for i in 0..n {
                                    let at = 4 + i * 2;
                                    if at + 2 > o.data.len() {
                                        break;
                                    }
                                    let off = u16::from_le_bytes([o.data[at], o.data[at + 1]]);
                                    if let Some(s) = re.strings.get(off) {
                                        if s == "loop_mfc" {
                                            errs.push(format!(
                                                "{path}: cloned DoAction still targets loop_mfc"
                                            ));
                                        } else if s == "loop_smfc" {
                                            stats.push(format!("{path}: DoAction -> loop_smfc"));
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
        // Label tables stay name-sorted (binary-searched by the engine).
        let names: Vec<&str> = sec.labels.iter().map(|l| l.name.as_str()).collect();
        let mut sorted = names.clone();
        sorted.sort();
        if names != sorted {
            errs.push(format!("{path}: label table unsorted"));
        }
        for (i, t) in sec.tags.iter().enumerate() {
            if let ap2::Tag::DefineSprite(sp) = t {
                walk(&sp.section, &format!("{path}/{i}"), re, new_sprites, errs, stats);
            }
        }
    }
    let mut errs = Vec::new();
    let mut stats = Vec::new();
    walk(&re.root, "root", &re, &new_sprites, &mut errs, &mut stats);
    if !errs.is_empty() {
        for e in &errs {
            println!("FAIL smarv-emblem: {e}");
        }
        return 1;
    }
    // Re-scramble the string table for bemaniutils consumption (its SWF
    // parser always runs the cipher).
    let mut out = out;
    let st_off = u32::from_le_bytes(out[48..52].try_into().unwrap()) as usize;
    let st_size = u32::from_le_bytes(out[52..56].try_into().unwrap()) as usize;
    let scrambled = ap2::encode_string_table(&out[st_off..st_off + st_size]);
    out[st_off..st_off + st_size].copy_from_slice(&scrambled);
    if std::fs::write(out_afp, &out).is_err() {
        println!("FAIL smarv-emblem: write {out_afp}");
        return 1;
    }
    for s in &stats {
        println!("    {s}");
    }
    println!(
        "smarv-emblem OK: shape {:?} -> {:?}, {} sprite clone(s), {} -> {} bytes",
        shape_ids,
        ids.shapes.iter().map(|(_, n)| *n).collect::<Vec<_>>(),
        ids.sprites.len(),
        data.len(),
        out.len()
    );
    0
}

/// Step-4 task-02 (Leg D): run the REAL GE2D label rewriter — the same
