#!/usr/bin/env python3
"""Extract assets from DDR Ultramix / Dancing Stage Unleashed archive files.

Two core archive formats are supported, both flat and sector-aligned to 0x800:

    x_data bin (textures, charts, song-info files, etc.)
      The table-of-contents comes in one of two forms, per game:

      "xbe"  (Ultramix) — a static array embedded in default.xbe.
             Each 16-byte entry: { name_va, size, size_aligned, offset }.
             `name_va` points at a NUL-terminated Shift-JIS filename in the
             XBE; it is resolved to a file offset via the XBE section headers.

      "hbn"  (Dancing Stage Unleashed 2) — a CRLF text sidecar next to the
             bin (x_data_<region>.hbn, written by Konami's x_bincat tool):
                 Konami Computer Entertainment Hawaii, Inc.
                 !! This file is auto-generated by x_bincat. ... !!
                 <count>
                 <name>,<offset>,<size>,<size_aligned>     (x count)
                 <largest size_aligned>
             Parsed by the XBE's loader (DSU2 default.xbe FUN_00056f90),
             which is what this parser mirrors.

    music sng (audio streams; XBOX-IMA ADPCM, 44.1 kHz stereo, headerless)
      The table-of-contents lives inside the archive itself, at a per-game
      offset: sector 0 for Ultramix; sector 1 (0x800) for DSU2, whose sector 0
      holds only the "Konami Computer Entertainment Hawaii, Inc." magic plus
      packer-tool padding (DSU2 default.xbe FUN_000b8000).
      Layout: u32 count, then `count` 20-byte entries of
      { tag[4], offset, size, loop_offset, loop_size }.
      `loop_*` describes a looping preview stream for song-wheel (zero for
      UI/non-song audio). Main streams are extracted as `{tag}.wavm`,
      loops as `{tag}_loop.wavm`.
      DSU3 uses the DSU2 layout, but one of its entries is a comment line ("// Begin US ")
      from the packer's input list. The game looks streams up by tag and never reads it, so
      the parser skips any entry whose tag starts with "//".

DSU2 and DSU3 also ship two more archive types (both optional per game):

    resource krc/krh (UI/stage textures; DSU2 default.xbe FUN_00095150)
      The .krc is a standard Xbox XPR0 bundle: { "XPR0", total_size,
      header_size }, then one 20-byte D3D resource header per texture
      { common, data, lock, format, size }, terminated by 0xFFFFFFFF. Texture
      bytes live at header_size + data. The .krh text sidecar names the
      resources in order ("#define *_texture_<name>_OFFSET <index*20>UL").
      Only linear DXT textures occur (and the game only accepts textures), so
      each is written as a plain .dds under resource/.

    voice BKT (announcer banks; DSU2 default.xbe FUN_000b6fd0/FUN_000b7030)
      Header { header_size, group_count, clip_count, group_off, clip_off }.
      Groups are { u16 first_clip, u8 play_chance, u8 clip_count }: the game
      plays a random clip of the group when rand_byte <= play_chance (255 =
      always). Clips are { start, end } byte ranges, followed by one kind byte
      per clip selecting the DirectSound voice pool (FUN_000b9f50):
      0 = PCM16 mono 22050 Hz, 1 = PCM16 stereo 22050 Hz, 2 = Xbox ADPCM
      stereo 44100 Hz. Clips are extracted raw (headerless) under
      voice/<bank>/g<group>_<n>.<ext>: `.pcm` for the PCM kinds and `.wavm`
      for Xbox ADPCM, so only true .sng-style streams carry the .wavm name.
      voice_manifest.csv records each clip's codec, channels and sample rate.

Dancing Stage Unleashed 3 (dsu3_eu) uses the same x_data, krc and BKT formats as DSU2.
Only VCLIP_M_e.BKT is in the rip. The XBE also names VCLIP_e and VCLIP_B_e, but those files
are not on the disc. Every DSU3 clip is kind 1 (PCM16 stereo).

DDR ULTRAMIX 4 (ultramix4_us) is the DSU3 layout again, with the files renamed per platform
(`*_XBOX_US.*`). Its music is split over four .sng archives (`music_XBOX_US_1..4.sng`), each
with its own TOC at 0x800; their tags are disjoint, so all streams land in one directory and
sng_manifest.csv records the source archive per stream. The voice bank sits at the disc root
(`VCLIP_M.BKT`).

Usage:
    extract_ultramix_data.py <game> <game_dir> <out_dir>

Examples:
    extract_ultramix_data.py ultramix_us ~/Desktop/ultramix ./extracted
    extract_ultramix_data.py dsu2_eu ~/Desktop/dsu2 ./extracted_dsu2
    extract_ultramix_data.py dsu3_eu ~/Desktop/dsu3 ~/Desktop/dsu3/extracted_full
    extract_ultramix_data.py ultramix4_us ~/Desktop/"DDR ISOs"/ultramix_4 ~/Desktop/"DDR ISOs"/ultramix_4/extracted_full
"""

