//! Jacket and thumbnail art for injected songs (design §4.6).
//!
//! `jacket` composes a 512² square from a song folder's art; `thumbnail`
//! turns it into the stock 192² BC1 DDS. This file adds the containers the
//! game opens — `arc/jacket/<b>_jk.arc` (one member `data/jacket/<b>_jk.png`,
//! **stored uncompressed**: an LZ77-compressed PNG member renders as a flat
//! coloured square, cabinet run 2026-10-21; `core::arc::ArcArchive` writes
//! uncompressed, so this is the default) and the series thumbnail arc
//! (`data/jacket/thumbnail/<b>_tn.dds` members) — plus the embedded
//! placeholder jacket (`data_mods/stepmania_packs/placeholder_jacket.png`,
//! generated by `scripts/gen_stepmania_placeholder.py`).
//!
//! `source.rs` (std), `jacket.rs` (`image`) and `thumbnail.rs` (`image` +
//! `texpresso`) are pure and mounted by `scripts/validate_stepmania.sh`;
//! this file is not (the arc writer logs through the DLL logger).

pub mod jacket;
pub mod source;
pub mod thumbnail;

use crate::core::arc::ArcArchive;
use image::RgbaImage;

pub use jacket::JACKET_SIZE;
pub use source::SourceKind;
pub use thumbnail::thumbnail_dds;

/// The shipped placeholder jacket (512² RGBA PNG).
pub const PLACEHOLDER_JACKET_PNG: &[u8] =
    include_bytes!("../../../data_mods/stepmania_packs/placeholder_jacket.png");

/// The placeholder decoded; falls back to a flat dark square if the embedded
/// PNG somehow fails to decode (it is a committed artefact, so this is a
/// build-time invariant rather than a runtime risk).
#[must_use]
pub fn placeholder_jacket() -> RgbaImage {
    jacket::decode(PLACEHOLDER_JACKET_PNG)
        .map(|img| jacket::square_from(SourceKind::Jacket, &img))
        .unwrap_or_else(|| {
            RgbaImage::from_pixel(JACKET_SIZE, JACKET_SIZE, image::Rgba([24, 26, 34, 255]))
        })
}

/// Member path of a jacket PNG inside its arc.
#[must_use]
pub fn jacket_member(basename: &str) -> String {
    format!("data/jacket/{basename}_jk.png")
}

/// Member path of a thumbnail DDS inside the series arc.
#[must_use]
pub fn thumbnail_member(basename: &str) -> String {
    format!("data/jacket/thumbnail/{basename}_tn.dds")
}

/// `arc/jacket/<b>_jk.arc` bytes for an encoded PNG.
#[must_use]
pub fn jacket_arc(basename: &str, png: Vec<u8>) -> Vec<u8> {
    let mut arc = ArcArchive::empty();
    arc.add_or_replace(jacket_member(basename), png);
    arc.to_bytes()
}

/// A series thumbnail arc from `(basename, dds bytes)` members.
#[must_use]
pub fn thumbnail_arc<I>(members: I) -> Vec<u8>
where
    I: IntoIterator<Item = (String, Vec<u8>)>,
{
    let mut arc = ArcArchive::empty();
    for (basename, dds) in members {
        arc.add_or_replace(thumbnail_member(&basename), dds);
    }
    arc.to_bytes()
}
